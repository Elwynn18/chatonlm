/** Vrai si `code` est dans les plages (recherche dichotomique). */
export function covers(ranges: Ranges, code: number): boolean {
  let low = 0;
  let high = ranges.length - 1;
  while (low <= high) {
    const middle = (low + high) >> 1;
    const range = ranges[middle];
    const [start, end] = typeof range === "number" ? [range, range] : range;
    if (code < start) high = middle - 1;
    else if (code > end) low = middle + 1;
    else return true;
  }
  return false;
}
